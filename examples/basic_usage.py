"""
Пример расчёта параметров стандартной атмосферы
по ГОСТ 4401-81.
"""

from src.atmosphere import atmosphere_geometrical


# Геометрическая высота, м
h = 10000

# Расчёт параметров атмосферы
g, T, p, rho, a, mu = atmosphere_geometrical(h)

# Вывод результатов
print(f"Геометрическая высота: {h:.2f} м")
print(f"Ускорение свободного падения: {g:.6f} м/с²")
print(f"Температура: {T:.2f} K")
print(f"Давление: {p:.2f} Па")
print(f"Плотность воздуха: {rho:.6f} кг/м³")
print(f"Скорость звука: {a:.3f} м/с")
print(f"Динамическая вязкость: {mu:.8e} Па·с")